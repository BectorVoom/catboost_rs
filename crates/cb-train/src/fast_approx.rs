//! Bit-exact ports of the approximate transcendentals upstream CatBoost uses to
//! store and update EXP-domain approxes for `IsStoreExpApprox` losses
//! (`approx_updater_helpers.h:60-72` — Logloss, CrossEntropy, Poisson,
//! LogLinQuantile, PairLogit(-Pairwise), YetiRank(-Pairwise)).
//!
//! Upstream deliberately does NOT use exact `exp`/`log` on the training-fold
//! approx pipeline:
//!
//! - per-LEAF delta exp-ification runs `fmath::expd_v`
//!   (`ExpApproxIf(TArrayRef<double>)` → `NCB::FastExpWithInfInplace` →
//!   `FastExpInplaceAvx2` → `contrib/libs/fmath/fmath.hpp expd_v`);
//! - per-DOC learning-rate application runs
//!   `fast_exp(FastLogf(delta) * lr)` (`ApplyLearningRate<true>`,
//!   `approx_updater_helpers.h:31-33`) — the table-based scalar `fast_exp` from
//!   `library/cpp/fast_exp/fast_exp.cpp` and the Mineiro `FastLogf` from
//!   `library/cpp/fast_log/fast_log.h`.
//!
//! Their approximation error (~1e-6 absolute in log space per application) is
//! NOT noise: it feeds the next iteration's derivatives, accumulates, and by
//! ~10-20 iterations moves greedy split scores across tie-break boundaries. An
//! engine computing exact `exp` diverges from upstream's chosen tree STRUCTURE
//! at iteration scale even when every formula matches (the
//! `ctr_borders_multiprior` 20-iteration localization, 2026-08-02, verified
//! against an instrumented v1.2.10 CLI build: identical fold leaf `(SumDer,
//! SumWeights, delta)` at iteration 0, diverging stored approx — the
//! `ApplyLearningRate` pipeline was the only remaining difference).
//!
//! Every function here is a straight transcription of the upstream source with
//! the same IEEE-754 f64/f32 operation order; the committed reference vectors
//! (`tests/fixtures/fast_approx_ref.txt`, generated by
//! `tests/fixtures/fast_approx_ref_generator.cpp.txt` compiled against the
//! REAL upstream objects) pin bit-for-bit equality.

use std::sync::OnceLock;

